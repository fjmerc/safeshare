// Interop test vectors for the end-to-end encryption format, produced by the
// web app's own internal/static/web/assets/crypto.js. The SDKs test against
// sdk/testdata/e2e-vectors.json, so a file they encrypt opens in the browser
// and a browser upload opens in the SDKs.
//
//   node tests/js/e2e-vectors.test.js          check the committed vectors still match crypto.js
//   node tests/js/e2e-vectors.test.js --write  regenerate them
//
// Runs crypto.js under Node's Web Crypto (same AES-GCM as browsers) with a
// fixed IV, so the expected ciphertexts are deterministic.

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { webcrypto } = require('crypto');

const repoRoot = path.resolve(__dirname, '..', '..');
const cryptoJs = path.join(repoRoot, 'internal/static/web/assets/crypto.js');
const vectorsPath = path.join(repoRoot, 'sdk/testdata/e2e-vectors.json');

const FIXED_IV = Uint8Array.from({ length: 12 }, (_, i) => 0xA0 + i);
const KEY_BYTES = Uint8Array.from({ length: 32 }, (_, i) => i);

function loadCrypto() {
    const sandbox = {
        window: {
            crypto: {
                subtle: webcrypto.subtle,
                getRandomValues: (a) => { a.set(FIXED_IV.subarray(0, a.length)); return a; },
            },
        },
        TextEncoder, TextDecoder, btoa, atob, Uint8Array, DataView, ArrayBuffer, Math, Number, Error, RangeError,
    };
    vm.createContext(sandbox);
    vm.runInContext(fs.readFileSync(cryptoJs, 'utf8'), sandbox, { filename: cryptoJs });
    return sandbox.window.SafeShareCrypto;
}

const hex = (buf) => Buffer.from(buf instanceof ArrayBuffer ? new Uint8Array(buf) : buf).toString('hex');
const bytes = (s) => new TextEncoder().encode(s);
const ab = (u8) => u8.buffer.slice(u8.byteOffset, u8.byteOffset + u8.byteLength);
function pattern(n) {
    const b = new Uint8Array(n);
    for (let i = 0; i < n; i++) b[i] = (i * 31 + 7) & 0xFF;
    return b;
}
function u32(n) { const b = new Uint8Array(4); new DataView(b.buffer).setUint32(0, n, true); return b; }
function u64(lo, hi) { const b = new Uint8Array(8); const v = new DataView(b.buffer); v.setUint32(0, lo, true); v.setUint32(4, hi, true); return b; }
function cat(...parts) { return Uint8Array.from(Buffer.concat(parts.map((p) => Buffer.from(p)))); }

async function generate() {
    const C = loadCrypto();
    const out = {
        description: 'Generated by tests/js/e2e-vectors.test.js from internal/static/web/assets/crypto.js. Do not edit by hand.',
        key: Buffer.from(KEY_BYTES).toString('base64url'),
        iv: hex(FIXED_IV),
        constants: { pad_min_bytes: C.PAD_MIN_BYTES, ciphertext_overhead: C.CIPHERTEXT_OVERHEAD },
        padme: [],
        padded_length: [],
        wrap: [],
        unwrap: [],
        encrypt: [],
        decrypt_fails: [],
        share_url: [],
    };

    const ns = [0, 1, 2, 3, 4, 5, 7, 8, 9, 15, 16, 17, 31, 32, 33, 63, 64, 65, 100, 255, 256, 257, 1000, 1023, 1024,
        1025, 4095, 4096, 4097, 65535, 65536, 65537, 1000000, 2147483647, 2147483648, 4294967297, 104857600,
        5000000000, 1099511640121, 9007199254740991];
    for (const n of ns) out.padme.push({ n, padded: C.padmeLength(n) });

    const pads = [[0, 0], [10, 0], [5000, 0], [5000, 6000], [5000, 5028], [5001, 5028], [100, 4200], [1000000, 1000128],
        [1000000, 0], [1000000, 2000000], [70000, 74000], [70000, 70100], [4096, 8220], [4097, 8220]];
    for (const [n, max] of pads) {
        try {
            out.padded_length.push({ n, max_stored: max, padded: C.paddedPayloadLength(n, max) });
        } catch (e) {
            out.padded_length.push({ n, max_stored: max, error: e.code || 'error' });
        }
    }

    const longName = 'a'.repeat(1030);
    const splitName = 'x'.repeat(1023) + 'é.txt'; // cut inside the two-byte é
    const wraps = [
        { id: 'sf01-basic', fn: 'v1', name: 'report.pdf', data: bytes('hello world') },
        { id: 'sf01-unicode', fn: 'v1', name: 'naïve 日本語.txt', data: bytes('data') },
        { id: 'sf01-long-name', fn: 'v1', name: longName, data: bytes('x') },
        { id: 'sf01-empty-data', fn: 'v1', name: 'empty.txt', data: new Uint8Array(0) },
        { id: 'sf02-basic', fn: 'v2', name: 'report.pdf', data: bytes('hello world'), max: 0 },
        { id: 'sf02-name-visible', fn: 'v2', name: '', data: bytes('hello world'), max: 0 },
        { id: 'sf02-unicode', fn: 'v2', name: 'naïve 日本語.txt', data: bytes('data'), max: 0 },
        { id: 'sf02-long-name', fn: 'v2', name: longName, data: bytes('x'), max: 0 },
        { id: 'sf02-split-utf8', fn: 'v2', name: splitName, data: bytes('x'), max: 0 },
        { id: 'sf02-bucket', fn: 'v2', name: 'big.bin', data: pattern(5000), max: 0 },
        { id: 'sf02-capped', fn: 'v2', name: 'big.bin', data: pattern(5000), max: 9200 },
        { id: 'sf02-near-limit', fn: 'v2', name: 'big.bin', data: pattern(5000), max: 5051 },
        { id: 'sf02-too-large', fn: 'v2', name: 'big.bin', data: pattern(5000), max: 5050 },
        { id: 'sf02-empty-data', fn: 'v2', name: '', data: new Uint8Array(0), max: 0 },
    ];
    const payloads = {};
    for (const w of wraps) {
        const entry = { id: w.id, format: w.fn === 'v1' ? 'SF01' : 'SF02', name: w.name, data: hex(w.data) };
        if (w.fn === 'v2') entry.max_stored = w.max;
        try {
            const p = w.fn === 'v1' ? C.wrapPayload(w.name, ab(w.data)) : C.wrapPayloadPadded(w.name, ab(w.data), w.max);
            entry.payload = hex(p);
            payloads[w.id] = p;
        } catch (e) {
            entry.error = e.code || 'error';
        }
        out.wrap.push(entry);
    }

    const pad16 = new Uint8Array(16);
    const unwraps = [
        ...Object.entries(payloads).map(([id, p]) => ({ id: 'wrapped-' + id, payload: new Uint8Array(p) })),
        { id: 'legacy-raw', payload: bytes('just a plain file') },
        { id: 'short-sf0', payload: bytes('SF0') },
        { id: 'sf01-zero-name', payload: cat(bytes('SF01'), u32(0), bytes('rest')) },
        { id: 'sf01-name-too-long', payload: cat(bytes('SF01'), u32(1025), new Uint8Array(1100)) },
        { id: 'sf01-name-past-end', payload: cat(bytes('SF01'), u32(10), bytes('abc')) },
        { id: 'sf01-exactly-8', payload: cat(bytes('SF01'), u32(0)) },
        { id: 'sf02-truncated', payload: cat(bytes('SF02'), u32(0), u32(1)) },
        { id: 'sf02-name-too-long', payload: cat(bytes('SF02'), u32(1025), u64(0, 0), new Uint8Array(1100)) },
        { id: 'sf02-data-past-end', payload: cat(bytes('SF02'), u32(0), u64(100, 0), new Uint8Array(50)) },
        { id: 'sf02-huge-length', payload: cat(bytes('SF02'), u32(0), u64(0, 0x200000), pad16) },
        { id: 'sf02-nonzero-padding', payload: cat(bytes('SF02'), u32(0), u64(2, 0), bytes('hi'), bytes('\x00\x00\x01')) },
        { id: 'sf02-zero-everything', payload: cat(bytes('SF02'), u32(0), u64(0, 0), pad16) },
    ];
    for (const u of unwraps) {
        const entry = { id: u.id, payload: hex(u.payload) };
        try {
            const r = C.unwrapPayload(ab(u.payload));
            entry.filename = r.filename;
            entry.data = hex(r.data);
            entry.version = r.version;
        } catch (e) {
            entry.error = true;
        }
        out.unwrap.push(entry);
    }

    const key = await C.importKey(out.key); // decrypt-only key
    const encKey = await webcrypto.subtle.importKey('raw', KEY_BYTES, { name: 'AES-GCM' }, false, ['encrypt']);
    const encryptCases = [
        { id: 'raw', payload: bytes('a raw file, name left visible') },
        { id: 'empty', payload: new Uint8Array(0) },
        { id: 'sf01-basic', payload: new Uint8Array(payloads['sf01-basic']) },
        { id: 'sf02-basic', payload: new Uint8Array(payloads['sf02-basic']) },
        { id: 'sf02-bucket', payload: new Uint8Array(payloads['sf02-bucket']) },
    ];
    for (const e of encryptCases) {
        const blob = new Uint8Array(await C.encryptFile(encKey, ab(e.payload)));
        const back = new Uint8Array(await C.decryptFile(key, ab(blob)));
        if (hex(back) !== hex(e.payload)) throw new Error('round trip failed for ' + e.id);
        out.encrypt.push({ id: e.id, payload: hex(e.payload), blob: hex(blob) });
    }
    const good = Buffer.from(out.encrypt[0].blob, 'hex');
    const tampered = Uint8Array.from(good); tampered[tampered.length - 1] ^= 1;
    const flippedIv = Uint8Array.from(good); flippedIv[0] ^= 1;
    for (const [id, blob] of [['tampered-tag', tampered], ['tampered-iv', flippedIv], ['iv-only', good.subarray(0, 12)],
        ['too-short', good.subarray(0, 5)]]) {
        let failed = false;
        try { await C.decryptFile(key, ab(Uint8Array.from(blob))); } catch (e) { failed = true; }
        if (!failed) throw new Error('decrypt unexpectedly succeeded: ' + id);
        out.decrypt_fails.push({ id, blob: hex(blob) });
    }

    for (const base of ['https://share.example.com', 'https://share.example.com/', 'http://abc.onion/sub/']) {
        const url = C.buildEncryptedUrl(base, 'Abc_123-xyz', out.key);
        const parsed = C.parseFragment(new URL(url).hash);
        out.share_url.push({ base, claim_code: 'Abc_123-xyz', key: out.key, url, parsed_code: parsed.claimCode, parsed_key: parsed.encryptionKey });
    }
    return out;
}

(async () => {
    const vectors = JSON.stringify(await generate(), null, 1) + '\n';
    if (process.argv.includes('--write')) {
        fs.mkdirSync(path.dirname(vectorsPath), { recursive: true });
        fs.writeFileSync(vectorsPath, vectors);
        console.log('wrote ' + path.relative(repoRoot, vectorsPath));
        return;
    }
    const committed = fs.existsSync(vectorsPath) ? fs.readFileSync(vectorsPath, 'utf8') : '';
    if (committed !== vectors) {
        console.log('FAIL sdk/testdata/e2e-vectors.json is out of date with crypto.js; run: node tests/js/e2e-vectors.test.js --write');
        process.exit(1);
    }
    console.log('PASS e2e vectors match crypto.js');
})().catch((e) => { console.log('FAIL ' + (e && e.stack || e)); process.exit(1); });
